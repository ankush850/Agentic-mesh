export const CriterionEvidenceSchema = z.object({
  criterionIndex: z.number(),
  elements: z.array(z.string()),
  source: z.string(),
});
export type CriterionEvidence = z.infer<typeof CriterionEvidenceSchema>;

export const GeneratedTicketSchema = z.object({
  key: z.string(),
  summary: z.string(),
  title: z.string(),
  description: z.string(),
  acceptanceCriteria: z.array(z.string()),
  labels: z.array(z.string()).default(["agentic-mesh-generated"]),
  evidence: z.array(CriterionEvidenceSchema).default([]),
  contentHash: z.string(),
  reviewNotice: z.string().default("auto-generated, needs human review"),
  isAutoGenerated: z.literal(true).default(true),
});
export type GeneratedTicket = z.infer<typeof GeneratedTicketSchema>;

export interface GenerateTicketOptions {
  appModel: AppModel;
  focus?: string;
  maxCriteria?: number;
  dryRun?: boolean;
  projectKey?: string;
  fixturesDir?: string;
}

