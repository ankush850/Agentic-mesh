import { useState } from "react";
import { useMutation } from "@tanstack/react-query";
import { Download, FileCode2, FileJson, FileText, Send, Ticket } from "lucide-react";
import type { RunDetail } from "../../../../shared/contracts";
import { api } from "../../lib/api";
import { toast } from "../../store/toast";
import { Button } from "../../components/ui/Button";
import { Card, CardBody, CardHeader } from "../../components/ui/Card";
import { Dialog } from "../../components/ui/Dialog";
import { Field, Input } from "../../components/ui/Field";
import { Badge } from "../../components/ui/Badge";

export function ExportTab({ detail }: { detail: RunDetail }) {
  const { summary } = detail;
  const [ticketKey, setTicketKey] = useState(summary.ticketKey ?? "");
  const [previewOpen, setPreviewOpen] = useState(false);
  const [preview, setPreview] = useState<string | null>(null);

  const jira = useMutation({
    mutationFn: (dryRun: boolean) => api.postToJira({ runId: summary.runId, ticketKey, dryRun }),
    onSuccess: (result, dryRun) => {
      setPreview(result.preview);
      if (dryRun) {
        setPreviewOpen(true);
      } else if (result.posted) {
        toast.success("Comment posted to Jira", `${ticketKey} now links to this run.`);
        setPreviewOpen(false);
      } else {
        toast.warning("Dry run only", "Jira is not configured on the server, so nothing was sent.");
      }
    },
    onError: (error: Error) => toast.error("Jira request failed", error.message),
  });

  const downloads = [
    {
      format: "html" as const,
      label: "HTML report",
      description: "Self-contained page with screenshots and repair history",
      icon: FileCode2,
    },
    {
      format: "md" as const,
      label: "Markdown",
      description: "Paste into a PR, wiki page or Jira comment",
      icon: FileText,
    },
    {
      format: "json" as const,
      label: "Raw JSON",
      description: "Machine-readable results for CI pipelines",
      icon: FileJson,
    },
  ];

  return (
    <div className="space-y-5">
      <Card>
        <CardHeader
          title="Export this run"
          description="Downloads are generated by the engine, not the browser."
        />
        <CardBody className="grid gap-3 sm:grid-cols-3">
          {downloads.map(({ format, label, description, icon: Icon }) => (
            <a
              key={format}
              href={api.exportUrl(summary.runId, format)}
              download
              className="group flex flex-col gap-2 rounded-xl border border-line bg-surface-2 p-4 transition-colors hover:border-accent/50"
            >
              <span className="flex items-center justify-between">
                <Icon className="h-4 w-4 text-accent" aria-hidden />
                <Download
                  className="h-3.5 w-3.5 text-muted transition-colors group-hover:text-fg"
                  aria-hidden
                />
              </span>
              <span className="text-sm font-medium text-fg">{label}</span>
              <span className="text-[11px] leading-relaxed text-muted">{description}</span>
            </a>
          ))}
        </CardBody>
      </Card>

      <Card>
        <CardHeader
          title="Post result to Jira"
          description="Always previews first; nothing is written without confirmation."
          actions={
            <Badge tone={summary.ticketKey ? "running" : "queued"}>
              {summary.ticketKey ?? "no ticket"}
            </Badge>
          }
        />
        <CardBody className="space-y-4">
          <div className="flex flex-wrap items-end gap-3">
            <Field label="Ticket key" className="min-w-56 flex-1">
              {(props) => (
                <Input
                  {...props}
                  value={ticketKey}
                  onChange={(event) => setTicketKey(event.target.value)}
                  placeholder="QA-101"
                />
              )}
            </Field>
            <Button
              variant="secondary"
              disabled={!ticketKey.trim()}
              loading={jira.isPending}
              onClick={() => jira.mutate(true)}
            >
              <Ticket className="h-4 w-4" aria-hidden />
              Preview comment
            </Button>
          </div>

          <p className="text-[11px] leading-relaxed text-muted">
            Posting requires <code className="font-mono text-fg">JIRA_BASE_URL</code>,{" "}
            <code className="font-mono text-fg">JIRA_EMAIL</code> and{" "}
            <code className="font-mono text-fg">JIRA_API_TOKEN</code> on the server. Credentials
            never reach the browser.
          </p>

          {jira.isError ? (
            <p role="alert" className="text-xs text-failed">
              {(jira.error as Error).message}
            </p>
          ) : null}
        </CardBody>
      </Card>

      <Dialog
        open={previewOpen}
        onClose={() => setPreviewOpen(false)}
        title="Comment preview"
        description={`This is exactly what will be posted to ${ticketKey || "the ticket"}.`}
        className="max-w-2xl"
        footer={
          <>
            <Button variant="ghost" onClick={() => setPreviewOpen(false)}>
              Cancel
            </Button>
            <Button loading={jira.isPending} onClick={() => jira.mutate(false)}>
              <Send className="h-4 w-4" aria-hidden />
              Post for real
            </Button>
          </>
        }
      >
        <pre className="whitespace-pre-wrap rounded-lg border border-line bg-surface-2 px-3 py-2 font-mono text-[11px] leading-relaxed text-fg">
          {preview ?? "Generating preview…"}
        </pre>
      </Dialog>
    </div>
  );
}
