// Grounding Validator
// ============================================================================

/**
 * Validates that a criterion references real elements in the AppModel.
 * Drops any hallucinated criterion that mentions items not present in the model.
 */
export function groundCriterion(
  criterion: string,
  index: number,
  appModel: AppModel
): CriterionEvidence | null {
  const lower = criterion.toLowerCase();
  const matchedElements: string[] = [];
  let sourceRef = "";

  // Check interactive elements (buttons, inputs, links)
  const allElements = appModel.interactiveElements?.length
    ? appModel.interactiveElements
    : appModel.pages.flatMap((p) => p.interactiveElements || []);

  for (const el of allElements) {
    let matched = false;
    const elText = el.visibleText || el.text;
    if (el.id && lower.includes(el.id.toLowerCase())) matched = true;
    else if (el.dataTestId && lower.includes(el.dataTestId.toLowerCase())) matched = true;
    else if (el.placeholder && lower.includes(el.placeholder.toLowerCase())) matched = true;
    else if (elText && elText.length > 2 && lower.includes(elText.toLowerCase())) matched = true;
    else if (el.name && lower.includes(el.name.toLowerCase())) matched = true;

    if (matched) {
      matchedElements.push(`<${el.tag}> ${el.id ? "#" + el.id : ""} "${elText || el.name || ""}"`);
      if (!sourceRef) {
        sourceRef = `${el.sourceFile}:${el.startLine}`;
      }
    }
  }

  // Check forms
  const allForms = appModel.forms?.length ? appModel.forms : appModel.pages.flatMap((p) => p.forms || []);
  for (const form of allForms) {
    if (form.id && lower.includes(form.id.toLowerCase())) {
      matchedElements.push(`form#${form.id}`);
      if (!sourceRef) sourceRef = `${form.sourceFile}:${form.startLine}`;
    }
  }

  // Check navigation links
  const allLinks = appModel.navigationLinks?.length
    ? appModel.navigationLinks
    : appModel.pages.flatMap((p) => p.links || []);
  for (const link of allLinks) {
    if (link.href && lower.includes(link.href.toLowerCase())) {
      matchedElements.push(`link[href="${link.href}"]`);
      if (!sourceRef) sourceRef = `${link.sourceFile}:${link.startLine}`;
    }
  }

  // Check pages
  for (const page of appModel.pages) {
    if (page.title && lower.includes(page.title.toLowerCase())) {
      matchedElements.push(`page "${page.title}"`);
      if (!sourceRef) sourceRef = `${page.file || page.routeOrFile}:1`;
    }
  }

  if (matchedElements.length === 0) {
    // Ungrounded criterion (invented elements)
    return null;
  }

  return {
    criterionIndex: index,
    elements: Array.from(new Set(matchedElements)),
    source: sourceRef || "appModel:1",
  };
}

// ============================================================================
// Offline Heuristic Generator
// ============================================================================

export function generateHeuristicCriteriaFromAppModel(
  appModel: AppModel,
  maxCriteria: number = 8
): { criteria: string[]; evidence: CriterionEvidence[] } {
  const criteria: string[] = [];
  const evidence: CriterionEvidence[] = [];

  const allForms = appModel.forms?.length ? appModel.forms : appModel.pages.flatMap((p) => p.forms || []);
  const allElements = appModel.interactiveElements?.length
    ? appModel.interactiveElements
    : appModel.pages.flatMap((p) => p.interactiveElements || []);
  const allLinks = appModel.navigationLinks?.length
    ? appModel.navigationLinks
    : appModel.pages.flatMap((p) => p.links || []);

  // 1. Generate scenarios from Forms
  for (const form of allForms) {
    if (criteria.length >= maxCriteria) break;

    const pageName = form.sourceFile.replace(/\.[^.]+$/, "");
    const submitBtn = allElements.find(
      (e) => e.formId === form.id && (e.tag === "button" || e.type === "submit")
    );
    const btnLabel = submitBtn?.visibleText || submitBtn?.text || submitBtn?.id || "Submit";

    if (form.fields.length > 0) {
      const fieldActions = form.fields
        .slice(0, 3)
        .map((fld) => `types into ${fld.name || fld.id || fld.placeholder || "input"}`)
        .join(" and ");

      const gherkin = `Given the ${pageName} page, when the user ${fieldActions} and clicks ${btnLabel}, the submission should process`;
      const idx = criteria.length;
      criteria.push(gherkin);
      evidence.push({
        criterionIndex: idx,
        elements: form.fields.map((f) => `${f.tag}[${f.name || f.id || ""}]`),
        source: `${form.sourceFile}:${form.startLine}`,
      });
    }

    // Required field validation scenario
    const reqField = form.fields.find((f) => f.required);
    if (reqField && criteria.length < maxCriteria) {
      const gherkinReq = `Given the ${pageName} page, when the user leaves the ${reqField.name || reqField.id || "required"} field empty and clicks ${btnLabel}, a validation error should be visible`;
      const idx = criteria.length;
      criteria.push(gherkinReq);
      evidence.push({
        criterionIndex: idx,
        elements: [`<${reqField.tag} required> #${reqField.id || reqField.name || ""}`],
        source: `${form.sourceFile}:${form.startLine}`,
      });
    }
  }

  // 2. Generate scenarios from Action Buttons
  const standaloneButtons = allElements.filter(
    (e) => e.tag === "button" && !e.formId && (e.visibleText || e.text)
  );
  for (const btn of standaloneButtons) {
    if (criteria.length >= maxCriteria) break;
    const btnText = btn.visibleText || btn.text;
    const gherkin = `Given the application page, when the user clicks '${btnText}', the expected UI update should occur`;
    const idx = criteria.length;
    criteria.push(gherkin);
    evidence.push({
      criterionIndex: idx,
      elements: [`button#${btn.id || ""} "${btnText}"`],
      source: `${btn.sourceFile}:${btn.startLine}`,
    });
  }

  // 3. Generate scenarios from Navigation Links
  for (const link of allLinks) {
    if (criteria.length >= maxCriteria) break;
    if (link.href && link.href !== "#" && !link.href.startsWith("http")) {
      const linkLabel = link.text || link.href;
      const gherkin = `Given the application page, when the user clicks the '${linkLabel}' link, they should navigate to '${link.href}'`;
      const idx = criteria.length;
      criteria.push(gherkin);
      evidence.push({
        criterionIndex: idx,
        elements: [`a[href="${link.href}"] "${linkLabel}"`],
        source: `${link.sourceFile}:${link.startLine}`,
      });
    }
  }

  // Fallback if no forms or buttons existed
  if (criteria.length === 0) {
    const pageTitle = appModel.pages[0]?.title || "Home";
    const file = appModel.pages[0]?.file || appModel.pages[0]?.routeOrFile || "index.html";
    criteria.push(
      `Given the ${pageTitle} page, the main page elements should be visible and interactive`
    );
    evidence.push({
      criterionIndex: 0,
      elements: [file],
      source: `${file}:1`,
    });
  }

  return { criteria, evidence };
}

// ============================================================================
// Core Ticket Generation Engine
// ============================================================================

export async function generateTicketFromAppModel(
  options: GenerateTicketOptions
): Promise<GeneratedTicket> {
  const { appModel, focus } = options;
  const maxCriteria = options.maxCriteria ?? 8;
  const dryRun = options.dryRun ?? true;
  const projectKey = options.projectKey || process.env.JIRA_PROJECT_KEY || "SQA";
  const genDir = options.fixturesDir || GENERATED_DIR_DEFAULT;

  fs.mkdirSync(genDir, { recursive: true });

  const status = getLLMStatus();
  const compressed = compressAppModel(appModel, { focusPage: focus });

  let rawSummary = "";
  let rawDescription = "";
  let draftCriteria: string[] = [];

  // Try LLM generation if credentials exist
  if (status.groqAvailable || status.geminiAvailable) {
    const prompt = `
You are Agentic-mesh's requirements engineer. Analyze the following Tree-Sitter optimized codebase context and generate a Jira ticket in project ${projectKey}.

Focus: ${focus || "Entire application"}
Pages: ${appModel.pages.map((p) => p.route).join(", ")}

Codebase Context:
${compressed.optimizedContext.slice(0, 12000)}

Requirements:
1. Provide a concise Jira "summary" describing the application/feature.
2. Provide a plain-text "description" summarizing what the app does and the pages covered.
3. Generate between 3 and ${maxCriteria} acceptanceCriteria in strict Gherkin format ("Given ... when ... then/should ...").
4. GROUNDING MANDATE: Every criterion MUST reference elements (buttons, inputs, links, forms) that actually exist in the provided Codebase Context. Do NOT invent shopping carts, payment forms, or buttons that are absent.
5. Provide explicit expected outcomes (concrete text, URL, or visibility).

Return JSON matching:
{
  "summary": "...",
  "description": "...",
  "acceptanceCriteria": [
    "Given ..., when ..., then ..."
  ]
}
`;

    try {
      const responseSchema = z.object({
        summary: z.string().min(1),
        description: z.string().min(1),
        acceptanceCriteria: z.array(z.string().min(5)).min(1),
      });

      const result = await generateJSON(prompt, responseSchema, {
        systemPrompt: "You are an expert QA requirements specialist who strictly grounds acceptance criteria in the AST model.",
        temperature: 0.1,
      });

      rawSummary = result.data.summary;
      rawDescription = result.data.description;
      draftCriteria = result.data.acceptanceCriteria;
      logger.info({ criteriaCount: draftCriteria.length }, "Generated criteria via LLM.");
    } catch (llmErr) {
      logger.warn({ llmErr }, "LLM ticket generation failed; falling back to offline heuristic.");
    }
  }

  // Offline Heuristic Fallback
  if (!rawSummary || draftCriteria.length === 0) {
    const appName = path.basename(appModel.repoPath);
    rawSummary = `${appName}: Automated End-to-End Test Suite`;
    const totalEls = appModel.interactiveElements?.length ?? appModel.pages.flatMap((p) => p.interactiveElements || []).length;
    const pageFiles = appModel.pages.map((p) => p.file || p.routeOrFile).join(", ");
    rawDescription = `Automated verification suite generated from AST parsing of ${appName}. Covers ${appModel.pages.length} pages (${pageFiles}) and ${totalEls} interactive elements.`;
    const heuristic = generateHeuristicCriteriaFromAppModel(appModel, maxCriteria);
    draftCriteria = heuristic.criteria;
  }

  // Apply Grounding Validation & Evidence Extraction
  const groundedCriteria: string[] = [];
  const groundedEvidence: CriterionEvidence[] = [];

  for (let i = 0; i < draftCriteria.length; i++) {
    const crit = draftCriteria[i];
    const ev = groundCriterion(crit, groundedCriteria.length, appModel);
    if (ev) {
      groundedCriteria.push(crit);
      groundedEvidence.push(ev);
    } else {
      logger.warn({ criterion: crit }, "Dropped ungrounded criterion (invented elements).");
    }

    if (groundedCriteria.length >= maxCriteria) break;
  }

  // If all criteria were dropped by strict grounding, use heuristic criteria
  if (groundedCriteria.length === 0) {
    const fallback = generateHeuristicCriteriaFromAppModel(appModel, maxCriteria);
    groundedCriteria.push(...fallback.criteria);
    groundedEvidence.push(...fallback.evidence);
  }

  // De-duplication check
  const contentHash = computeTicketHash(rawSummary, groundedCriteria);
  const existingTicket = findExistingTicketByHash(contentHash, genDir);
  if (existingTicket) {
    logger.info({ key: existingTicket.key, hash: contentHash }, "Found existing duplicate ticket; returning cached ticket.");
    return existingTicket;
  }

  // Generate next free SQA-N key
  const freeKey = getNextFreeTicketKey(projectKey, genDir);

  const ticketData: GeneratedTicket = {
    key: freeKey,
    summary: rawSummary,
    title: rawSummary,
    description: rawDescription,
    acceptanceCriteria: groundedCriteria,
    labels: ["agentic-mesh-generated"],
    evidence: groundedEvidence,
    contentHash,
    reviewNotice: "auto-generated, needs human review",
    isAutoGenerated: true,
  };

  const validatedTicket = GeneratedTicketSchema.parse(ticketData);

  // Always save to fixtures/generated-tickets/<key>.json
  const savePath = path.join(genDir, `${validatedTicket.key}.json`);
  fs.writeFileSync(savePath, JSON.stringify(validatedTicket, null, 2), "utf-8");
  logger.info({ savePath, key: validatedTicket.key }, "Saved generated ticket to fixture file.");

  // If Jira credentials configured and dryRun is false, create the issue in Jira
  if (!dryRun && isBugReporterConfigured()) {
    try {
      const baseUrl = (process.env.JIRA_BASE_URL ?? "").replace(/\/$/, "");
      const email = process.env.JIRA_EMAIL ?? "";
      const apiToken = process.env.JIRA_API_TOKEN ?? "";
      const auth = Buffer.from(`${email}:${apiToken}`).toString("base64");

      const adfDesc = {
        type: "doc",
        version: 1,
        content: [
          {
            type: "paragraph",
            content: [{ type: "text", text: validatedTicket.description }],
          },
          {
            type: "heading",
            attrs: { level: 3 },
            content: [{ type: "text", text: "Acceptance Criteria (Auto-Generated)" }],
          },
          {
            type: "bulletList",
            content: validatedTicket.acceptanceCriteria.map((c) => ({
              type: "listItem",
              content: [
                {
                  type: "paragraph",
                  content: [{ type: "text", text: c }],
                },
              ],
            })),
          },
        ],
      };

      const res = await fetch(`${baseUrl}/rest/api/3/issue`, {
        method: "POST",
        headers: {
          Authorization: `Basic ${auth}`,
          "Content-Type": "application/json",
          Accept: "application/json",
        },
        body: JSON.stringify({
          fields: {
            project: { key: projectKey },
            issuetype: { name: "Task" },
            summary: `[Agentic-mesh] ${validatedTicket.summary}`,
            description: adfDesc,
            labels: validatedTicket.labels,
          },
        }),
      });

      if (res.ok) {
        const json = (await res.json()) as { key?: string };
        if (json.key) {
          logger.info({ realKey: json.key }, "Created real Jira ticket successfully.");
          validatedTicket.key = json.key;
        }
      }
    } catch (jiraErr) {
      logger.warn({ jiraErr }, "Failed to create real Jira issue, returned local SQA key.");
    }
  }

  return validatedTicket;
}
