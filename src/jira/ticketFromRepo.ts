const GENERATED_DIR_DEFAULT = path.resolve(process.cwd(), "fixtures/generated-tickets");

/**
 * Computes deterministic SHA-256 hash of summary and acceptance criteria.
 */
export function computeTicketHash(summary: string, criteria: string[]): string {
  const payload = `${summary.trim()}::${criteria.map((c) => c.trim()).join("::")}`;
  return crypto.createHash("sha256").update(payload).digest("hex");
}

/**
 * Finds the next available SQA-N key by scanning demo-tickets.json and fixtures/generated-tickets/.
 */
export function getNextFreeTicketKey(projectKey: string = "SQA", baseDir?: string): string {
  let highestN = 10; // Default starts at SQA-10 / SQA-11

  // 1. Scan fixtures/demo-tickets.json
  const demoTicketsPath = path.resolve(process.cwd(), "fixtures/demo-tickets.json");
  if (fs.existsSync(demoTicketsPath)) {
    try {
      const demoTickets = JSON.parse(fs.readFileSync(demoTicketsPath, "utf-8"));
      if (Array.isArray(demoTickets)) {
        for (const t of demoTickets) {
          const match = (t.key || "").match(/^SQA-(\d+)$/i);
          if (match) {
            const num = parseInt(match[1], 10);
            if (num > highestN) highestN = num;
          }
        }
      }
    } catch {}
  }

  // 2. Scan fixtures/generated-tickets/*.json
  const genDir = baseDir || GENERATED_DIR_DEFAULT;
  if (fs.existsSync(genDir)) {
    try {
      const files = fs.readdirSync(genDir);
      for (const file of files) {
        const match = file.match(/^SQA-(\d+)\.json$/i);
        if (match) {
          const num = parseInt(match[1], 10);
          if (num > highestN) highestN = num;
        }
      }
    } catch {}
  }

  return `${projectKey}-${highestN + 1}`;
}

/**
 * Checks if a ticket with the same content hash already exists.
 */
export function findExistingTicketByHash(
  hash: string,
  genDir: string = GENERATED_DIR_DEFAULT
): GeneratedTicket | null {
  if (!fs.existsSync(genDir)) return null;

  try {
    const files = fs.readdirSync(genDir);
    for (const file of files) {
      if (!file.endsWith(".json")) continue;
      const fullPath = path.join(genDir, file);
      const parsed = JSON.parse(fs.readFileSync(fullPath, "utf-8"));
      if (parsed.contentHash === hash) {
        return GeneratedTicketSchema.parse(parsed);
      }
    }
  } catch {}

  return null;
}

